// Arabic translations for the live seed's corpus (`content.ts`; ADR-166:
// Arabic is the first locale).
//
// Every course, section, lesson, quiz and video topic is translated WHOLE,
// because Arabic has no fallback locale: a lesson with no Arabic row is not
// shown in English, it is "not translated", so a half-translated course would
// be a curriculum with holes in it.
//
// Keyed by the ENGLISH course slug, section title, lesson slug, quiz slug and
// video-topic slug — a section has no slug of its own, so its English title is
// the key, the way `seed-learn-ar.ts` keys one. The Arabic rows KEEP the
// English slugs (ADR-181). Only the words are here: slugs, tracks, images,
// video ids, URLs, difficulty, durations and correct answers stay in
// `content.ts`. Every body keeps its English source's tags and hrefs one for
// one; pairs, tickers, figures and formulas are unchanged.
//
// Quiz questions are matched by POSITION and their options keep the English
// order, because `correctAnswer` is an index into `options` (ADR-058 #2).
// Attachment and link labels are maps from the English label, the shape
// `LessonTranslation.attachmentLabels` and `VideoTopicTranslation.linkLabels`
// store (ADR-161 #8). A video topic's `content` is the Arabic form of
// `videoBody()` in `run.ts`, written out in full.

export interface ArabicSection {
  title: string;
  description: string;
}

export interface ArabicLesson {
  title: string;
  summary: string;
  content: string;
  /** `learningObjectives`, in the English order. */
  objectives: string[];
  seoTitle: string;
  seoDescription: string;
  /** `seoFocusKeyword`. */
  keyword: string;
  /** English label → Arabic; present only on the lesson carrying the course's cheat sheet. */
  attachmentLabels?: Record<string, string>;
}

export interface ArabicCourse {
  title: string;
  summary: string;
  description: string;
  seoTitle: string;
  seoDescription: string;
  /** `seoFocusKeyword`. */
  keyword: string;
  /** Keyed by the section's English title. */
  sections: Record<string, ArabicSection>;
  /** Keyed by the lesson's English slug. */
  lessons: Record<string, ArabicLesson>;
}

export interface ArabicQuizQuestion {
  prompt: string;
  /** Same length and order as the English options. */
  options: string[];
  /** Same length as the English explanations, when the English has them. */
  explanations?: string[];
}

export interface ArabicQuiz {
  title: string;
  description: string;
  /** Same order as the English questions. */
  questions: ArabicQuizQuestion[];
}

export interface ArabicVideoTopic {
  title: string;
  summary: string;
  content: string;
  seoTitle: string;
  seoDescription: string;
  /** `seoFocusKeyword`. */
  keyword: string;
  /** English label → Arabic, when the English topic has links. */
  linkLabels?: Record<string, string>;
}

