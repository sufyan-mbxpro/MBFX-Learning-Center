/** Writes Arabic topic and term rows. Returns `{ topics, terms }` created. */
export async function seedArabicGlossary(
  db: PrismaClient,
): Promise<{ topics: number; terms: number }> {
  let topics = 0;
  for (const [slug, words] of Object.entries(GLOSSARY_TOPICS_AR)) {
    const english = await db.glossaryTopicTranslation.findUnique({
      where: { locale_slug: { locale: "en", slug } },
      select: { topicId: true },
    });
    if (!english) continue;
    const taken = await db.glossaryTopicTranslation.findFirst({
      where: { locale: "ar", OR: [{ topicId: english.topicId }, { slug }] },
      select: { id: true },
    });
    if (taken) continue;
    await db.glossaryTopicTranslation.create({
      data: {
        topicId: english.topicId,
        locale: "ar",
        name: words.name,
        slug,
        description: words.description,
        translationStatus: "TRANSLATED",
      },
    });
    topics += 1;
  }

  let terms = 0;
  for (const [slug, words] of Object.entries(GLOSSARY_TERMS_AR)) {
    const english = await db.glossaryTermTranslation.findUnique({
      where: { locale_slug: { locale: "en", slug } },
      select: { termId: true },
    });
    if (!english) continue;
    const taken = await db.glossaryTermTranslation.findFirst({
      where: { locale: "ar", OR: [{ termId: english.termId }, { slug }] },
      select: { id: true },
    });
    if (taken) continue;
    await db.glossaryTermTranslation.create({
      data: {
        termId: english.termId,
        locale: "ar",
        term: words.term,
        slug,
        simpleExplanation: words.simple,
        detailedExplanation: words.detailed ?? null,
        advancedExplanation: words.advanced ?? null,
        exampleScenario: words.example ?? null,
        faq: words.faq ?? undefined,
        translationStatus: "TRANSLATED",
      },
    });
    terms += 1;
  }
  return { topics, terms };
}
