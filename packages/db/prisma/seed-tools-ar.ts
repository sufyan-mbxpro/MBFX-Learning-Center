/** Writes the Arabic row for every seeded tool that has none. Returns how many it created. */
export async function seedArabicTools(db: PrismaClient): Promise<number> {
  let created = 0;
  for (const [key, words] of Object.entries(TOOLS_AR)) {
    const tool = await db.tool.findUnique({
      where: { key },
      select: { id: true, translations: { where: { locale: "ar" }, select: { id: true } } },
    });
    if (!tool || tool.translations.length > 0) continue;
    await db.toolTranslation.create({
      data: {
        toolId: tool.id,
        locale: "ar",
        title: words.title,
        tagline: words.tagline,
        intro: words.intro,
        body: words.body,
        highlights: words.highlights,
        ...(words.faq ? { faq: words.faq } : {}),
        ...(words.seoFocusKeyword ? { seoFocusKeyword: words.seoFocusKeyword } : {}),
        seoTitle: words.title,
        seoDescription: words.tagline,
        translationStatus: "TRANSLATED",
      },
    });
    created += 1;
  }
  return created;
}
